// Measures the sections that use `content-visibility: auto` and prints the `contain-intrinsic-size` rules to paste into
// source/css/foundation/layout.css. Chromium runs on software GL (never the GPU) against tools/serve.mjs on a free port, with the
// site's own self-hosted fonts, so what is measured is what a visitor gets.
//
// A section that has not rendered yet is laid out with its placeholder height, so a jump to it lands off target by the
// difference between that placeholder and the height it has once rendered. For every width and language this tool reads:
//   reserved  the height the CSS reserves (content box; Chrome adds the section padding and border on top)
//   real      the content-box height once the section is rendered and has built what it builds on becoming visible
//             (the load test is read idle: it starts running when visible and grows while it does)
//   landing   (with --landing) how far from the top of the window a section ends up after an instant jump to it from a fresh page
//
// usage: node tools/measure-sections.mjs [--help] [--widths 360,412,1280] [--langs pt,en] [--tolerance 30]
//                                        [--touch-below 1000] [--landing] [--table] [--css] [--write]
//                                        [--save file.json] [--load file.json] [--check file.json] [--no-switches] [--jobs 3]
//   --tolerance    the largest gap, in px, allowed between the printed polyline and any measured height (default 30). Heights are
//                  measured at the given widths and joined by straight lines (calc(A + B vw)) between the widths that matter;
//                  layout switches found in the stylesheets (width media queries in either notation, and container queries, whose
//                  switch is found by trying window widths) are never joined across
//   --save/--load  keep the measurements in a JSON file, or reuse one instead of measuring again
//   --jobs         how many pages to measure at once (default 3)
//   --no-switches  do not add the widths on both sides of every layout switch (they are measured by default)
//                  (the widths in KEEP, common phone, tablet and monitor widths, are added too and stay exact)
//   --check        measurements at other widths (a --save file): print how far the printed CSS is from them
//   --touch-below  widths under this many px are measured as touch devices (isMobile, 2.625 pixel ratio), like the E2E mobile project
//   --landing      also measure the landing offsets (reloads the page once per section, so it is slow)
//   --table        print every measurement; --css print the rules (both are on when neither --css nor --write is given)
//   --write        put the rules into source/css/foundation/layout.css, between its two `measure-sections` comments
