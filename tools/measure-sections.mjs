const withLanding = Arguments.flag('landing');
const jobs = Number(Arguments.list('jobs', ['3'])[0]);
const touchBelow = Number(Arguments.list('touch-below', ['1000'])[0]);
const wantsWrite = Arguments.flag('write');
const wantsTable = Arguments.flag('table') || !(Arguments.flag('css') || wantsWrite);
const wantsCss = Arguments.flag('css') || !(Arguments.flag('table') || wantsWrite);
const loadFrom = Arguments.list('load', null)?.[0];
const saveTo = Arguments.list('save', null)?.[0];
const checkWith = Arguments.list('check', null)?.[0];

const measureAll = async () => {
  const server = await SiteServer.start();
  const browser = await chromium.launch({ args: SOFTWARE_GL });
  try {
    const origin = `http://127.0.0.1:${server.port}`;
    const switches = Breakpoints.tidy([
      ...Breakpoints.media(),
      ...(await ContainerSwitches.find(browser, origin, Breakpoints.containers())),
    ]);
    // Every layout switch is measured on both sides (width and width - 1), so no line has to stretch past a measurement.
    const switchWidths = noSwitches ? [] : switches.flatMap((width) => [width - 1, width]);
    const widths = [
      ...new Set([
        ...Arguments.list('widths', DEFAULT_WIDTHS).map(Number),
        ...switchWidths,
        ...(noSwitches ? [] : KEEP),
      ]),
    ].sort((a, b) => a - b);
    const measurer = new SectionMeasurer({ browser, origin, touchBelow });
    const queue = languages.flatMap((language) => widths.map((width) => ({ language, width })));
    const measured = [];
    await Promise.all(
      Array.from({ length: jobs }, async () => {
        for (let job = queue.shift(); job; job = queue.shift())
          measured.push(await measurer.measure(job.language, job.width, withLanding));
      }),
    );
    return {
      switches,
      rows: measured.sort((a, b) => a.language.localeCompare(b.language) || a.width - b.width),
    };
  } finally {
    await browser.close();
    server.stop();
  }
};

const measurements = loadFrom ? JSON.parse(readFileSync(loadFrom, 'utf8')) : await measureAll();
const { rows } = measurements;
if (saveTo) writeFileSync(saveTo, JSON.stringify(measurements));
if (wantsTable) {
  console.log(
    `viewport height ${VIEWPORT_HEIGHT}\nlayout switches (window widths, px): ${measurements.switches.join(', ')}\n`,
  );
  console.log('lang  width  ' + SECTIONS.map((id) => id.padEnd(30)).join(''));
  console.log(
    '               ' +
      SECTIONS.map(() => `reserved  real  diff${withLanding ? '  landing' : '         '}   `).join(
        '',
      ),
  );
  for (const row of rows)
    console.log(
      `${row.language.padEnd(5)} ${String(row.width).padStart(5)}  ${SECTIONS.map((id) => `${String(Math.round(row.reserved[id])).padStart(6)} ${String(row.real[id]).padStart(6)} ${String(Math.round(row.real[id] - row.reserved[id])).padStart(5)} ${withLanding ? String(row.landing[id]).padStart(7) : '       '}   `).join('')}`,
    );
}
if (wantsCss || wantsWrite) {
  const css = new PlaceholderCss(measurements, tolerance);
  console.log(`\n${css.summary()}`);
  if (wantsCss) console.log(`\n${css.css()}`);
  if (wantsWrite) {
    writeFileSync(LAYOUT_CSS, css.patch(readFileSync(LAYOUT_CSS, 'utf8')));
    console.log(`\nwrote the rules into ${LAYOUT_CSS}`);
  }
  if (checkWith)
    console.log(
      `\nagainst the widths in ${checkWith}:\n${css.checkAgainst(JSON.parse(readFileSync(checkWith, 'utf8')).rows)}`,
    );
}
