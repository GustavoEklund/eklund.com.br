/** tools/serve.mjs started as its own process on a free port. */
class SiteServer {
  #child;
  port;

  static async start() {
    const server = new SiteServer();
    server.port = await SiteServer.#freePort();
    server.#child = spawn(
      process.execPath,
      [join(PROJECT, 'tools', 'serve.mjs'), '--port', String(server.port)],
      { cwd: PROJECT },
    );
    await new Promise((resolve, reject) => {
      server.#child.stdout.once('data', resolve);
      server.#child.once('error', reject);
      server.#child.once('exit', (code) => reject(new Error(`serve.mjs exited with ${code}`)));
    });
    return server;
  }

  static #freePort() {
    return new Promise((resolve) => {
      const probe = createServer().listen(0, '127.0.0.1', () => {
        const { port } = probe.address();
        probe.close(() => resolve(port));
      });
    });
  }

  stop() {
    this.#child.kill('SIGTERM');
  }
}

/** The widths at which the stylesheets switch layout. Queries are read in both notations: `(min-width: 900px)` and `(width >= 900px)`. */
class Breakpoints {
  /** The media queries: every minimum width, and every maximum width plus one. */
  static media() {
    const widths = new Set();
    for (const css of Breakpoints.#stylesheets()) {
      for (const [, prelude] of css.matchAll(/@media([^{]*)\{/g)) {
        for (const [, width] of prelude.matchAll(
          /\(\s*(?:min-width\s*:|width\s*>=)\s*(\d+)px\s*\)/g,
        ))
          widths.add(Number(width));
        for (const [, width] of prelude.matchAll(/\(\s*width\s*>\s*(\d+)px\s*\)/g))
          widths.add(Number(width) + 1);
        for (const [, width] of prelude.matchAll(
          /\(\s*(?:max-width\s*:|width\s*<=)\s*(\d+)px\s*\)/g,
        ))
          widths.add(Number(width) + 1);
        for (const [, width] of prelude.matchAll(/\(\s*width\s*<\s*(\d+)px\s*\)/g))
          widths.add(Number(width));
      }
    }
    return [...widths];
  }

  /** The container queries on a minimum width, [{ name, value, unit }]. Their switch is at a window width that has to be found by trying. */
  static containers() {
    const queries = new Map();
    for (const css of Breakpoints.#stylesheets()) {
      for (const [, name, value, unit] of css.matchAll(
        /@container\s+([\w-]+)\s*\(\s*(?:min-width\s*:|width\s*>=)\s*([\d.]+)(px|em)\s*\)/g,
      )) {
        queries.set(`${name} ${value}${unit}`, { name, value: Number(value), unit });
      }
    }
    return [...queries.values()];
  }

  /** Sorted, and widths one or two px apart (900 and 901) counted as one switch. */
  static tidy(widths) {
    return [...new Set(widths)]
      .sort((a, b) => a - b)
      .filter((width, index, all) => index === 0 || width - all[index - 1] > 2);
  }

  static #stylesheets() {
    const sheets = [];
    const walk = (directory) => {
      for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) {
          walk(path);
          continue;
        }
        if (!path.endsWith('.css')) continue;
        // The placeholder rules are generated from these switches, not one of them.
        sheets.push(readFileSync(path, 'utf8').replace(GENERATED_BLOCK, ''));
      }
    };
    walk(join(PROJECT, 'source', 'css'));
    return sheets;
  }
}

/**
 * The window width at which each container query starts to hold. A container query looks at the width of an element, and with
 * `em` at its font size too, and both follow the window (the body text is fluid), so the width is found by halving the range
 * between the narrowest and the widest window until the query flips.
 */
class ContainerSwitches {
  static #NARROWEST = 320;
  static #WIDEST = 1920;

  static async find(browser, origin, queries) {
    if (queries.length === 0) return [];
    const context = await browser.newContext({
      viewport: { width: ContainerSwitches.#WIDEST, height: VIEWPORT_HEIGHT },
      locale: 'pt-BR',
      timezoneId: 'America/Sao_Paulo',
    });
    try {
      const page = await context.newPage();
      await page.goto(`${origin}/`);
      await page.waitForFunction(
        () => document.documentElement.classList.contains('fonts-ready'),
        null,
        { timeout: 20000 },
      );
      const found = [];
      for (const query of queries) {
        const width = await ContainerSwitches.#flip(page, query);
        if (width !== null) found.push(width);
      }
      return found;
    } finally {
      await context.close();
    }
  }

  /** The narrowest window width at which the query holds, or null when it holds at none or at every width tried. */
  static async #flip(page, query) {
    let [below, above] = [ContainerSwitches.#NARROWEST, ContainerSwitches.#WIDEST];
    if (
      (await ContainerSwitches.#holds(page, query, below)) ||
      !(await ContainerSwitches.#holds(page, query, above))
    )
      return null;
    while (above - below > 1) {
      const middle = Math.floor((below + above) / 2);
      if (await ContainerSwitches.#holds(page, query, middle)) above = middle;
      else below = middle;
    }
    return above;
  }

  static async #holds(page, query, width) {
    await page.setViewportSize({ width, height: VIEWPORT_HEIGHT });
    await SectionMeasurer.settle(page);
    return page.evaluate(({ name, value, unit }) => {
      const container = [...document.querySelectorAll('*')].find(
        (element) => getComputedStyle(element).containerName === name,
      );
      const style = getComputedStyle(container);
      const inline =
        container.getBoundingClientRect().width -
        ['paddingLeft', 'paddingRight', 'borderLeftWidth', 'borderRightWidth'].reduce(
          (sum, side) => sum + Number.parseFloat(style[side]),
          0,
        );
      return inline >= (unit === 'em' ? value * Number.parseFloat(style.fontSize) : value);
    }, query);
  }
}

/** One language at one width: what the CSS reserves and what the sections really measure. */
class SectionMeasurer {
  #browser;
  #origin;
  #touchBelow;

  constructor({ browser, origin, touchBelow }) {
    this.#browser = browser;
    this.#origin = origin;
    this.#touchBelow = touchBelow;
  }

  async measure(language, width, withLanding) {
    const touch =
      this.#touchBelow > width ? { isMobile: true, hasTouch: true, deviceScaleFactor: 2.625 } : {};
    const context = await this.#browser.newContext({
      viewport: { width, height: VIEWPORT_HEIGHT },
      locale: LANGUAGES[language].tag,
      timezoneId: 'America/Sao_Paulo',
      ...touch,
    });
    try {
      const page = await this.#open(context, language);
      const reserved = await this.#reserved(page);
      const real = await this.#real(page);
      await page.close();
      const landing = withLanding ? await this.#landing(context, language) : null;
      return { language, width, reserved, real, landing };
    } finally {
      await context.close();
    }
  }

  async #open(context, language) {
    const page = await context.newPage();
    await page.goto(`${this.#origin}${LANGUAGES[language].path}`);
    await page.waitForFunction(
      () => document.documentElement.classList.contains('fonts-ready'),
      null,
      { timeout: 20000 },
    );
    await page.waitForLoadState('networkidle');
    await SectionMeasurer.settle(page);
    return page;
  }

  static async settle(page) {
    await page.evaluate(
      () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
    );
  }

  /**
   * Two frames, then until the transitions inside the section have ended. The history opens its first card when it becomes visible
   * and the card grows for about half a second, 130 px on a phone, so what is read earlier depends on how busy the machine is.
   */
  static async settleTransitions(page, id) {
    await SectionMeasurer.settle(page);
    await page.evaluate(
      (target) =>
        Promise.all(
          document
            .getElementById(target)
            .getAnimations({ subtree: true })
            .filter((animation) => animation instanceof CSSTransition)
            .map((animation) => animation.finished.catch(() => undefined)),
        ),
      id,
    );
    await SectionMeasurer.settle(page);
  }

  /** The content-box height each section reserves, read from the computed style. */
  async #reserved(page) {
    return page.evaluate(
      (ids) =>
        Object.fromEntries(
          ids.map((id) => [
            id,
            Number.parseFloat(
              getComputedStyle(document.getElementById(id)).containIntrinsicBlockSize.replace(
                'auto',
                '',
              ),
            ),
          ]),
        ),
      SECTIONS,
    );
  }

  /** Jumps straight to each section from the top of a fresh page and reports where its top edge ends up. */
  async #landing(context, language) {
    const landing = {};
    for (const id of SECTIONS) {
      const page = await this.#open(context, language);
      await page.evaluate(
        (target) =>
          document.getElementById(target).scrollIntoView({ behavior: 'instant', block: 'start' }),
        id,
      );
      await SectionMeasurer.settle(page);
      landing[id] = await page.evaluate(
        (target) => Math.round(document.getElementById(target).getBoundingClientRect().top),
        id,
      );
      await page.close();
    }
    return landing;
  }

  /**
   * The height of each section the moment it has rendered for the first time, which is the height the placeholder stood in for.
   * Every section is rendered at once and read idle; then the page is jumped to each section in turn and read once whatever the
   * section builds on becoming visible has run and its transitions have ended (the history opens its first card, the dashboard
   * draws). Nothing is read later than that on purpose: the history moves on to its next card every 9 s, and the load test
   * starts when it becomes visible and keeps growing while it runs, so the load test is read idle, before any scrolling.
   */
  async #real(page) {
    // Set through the CSSOM: the page's Content Security Policy forbids an injected <style>.
    await page.evaluate(
      (ids) =>
        ids.forEach((id) =>
          document
            .getElementById(id)
            .style.setProperty('content-visibility', 'visible', 'important'),
        ),
      SECTIONS,
    );
    await SectionMeasurer.settle(page);
    const idle = await SectionMeasurer.#contentHeights(page);
    const heights = {};
    for (const id of SECTIONS) {
      if (IDLE_SECTIONS.includes(id)) {
        heights[id] = idle[id];
        continue;
      }
      await page.evaluate(
        (target) =>
          document.getElementById(target).scrollIntoView({ behavior: 'instant', block: 'start' }),
        id,
      );
      await SectionMeasurer.settleTransitions(page, id);
      heights[id] = (await SectionMeasurer.#contentHeights(page))[id];
    }
    return heights;
  }

  static #contentHeights(page) {
    return page.evaluate(
      (ids) =>
        Object.fromEntries(
          ids.map((id) => {
            const element = document.getElementById(id),
              style = getComputedStyle(element);
            return [
              id,
              Math.round(
                element.clientHeight -
                  Number.parseFloat(style.paddingTop) -
                  Number.parseFloat(style.paddingBottom),
              ),
            ];
          }),
        ),
      SECTIONS,
    );
  }
}

/**
 * The placeholder of one section in one language as a polyline through measured heights: Ramer-Douglas-Peucker keeps the
 * fewest measured widths such that every dropped one is within `tolerance` px of the line between its kept neighbors.
 * It never joins widths on different sides of a layout switch, because the height jumps there.
 */
class Polyline {
  /** Rules [{ from, intercept, slope }] meaning height = intercept + slope * viewport width (slope in px per px of width). */
  static rules(points, switches, tolerance, keep = []) {
    const rules = [];
    const stretches = [0, ...switches].map((from, index, all) => [
      from,
      all[index + 1] ?? Infinity,
    ]);
    for (const [from, to] of stretches) {
      const inside = points.filter((point) => point.width >= from && point.width < to);
      if (inside.length === 0) continue;
      const knots = Polyline.#simplify(inside, tolerance, keep);
      if (knots.length === 1) {
        rules.push({ from, intercept: knots[0].height, slope: 0 });
        continue;
      }
      knots.slice(0, -1).forEach((knot, index) => {
        const next = knots[index + 1];
        const slope =
          Math.round(((next.height - knot.height) / (next.width - knot.width)) * 1e5) / 1e5;
        rules.push({
          from: index === 0 ? from : knot.width,
          intercept: Math.round(knot.height - slope * knot.width),
          slope,
        });
      });
    }
    return rules;
  }

  /** Keeps the widths whose neighbors' line misses them by more than they allow: `tolerance` px, or 1 px for the widths in `keep`. */
  static #simplify(points, tolerance, keep) {
    if (points.length <= 2) return points;
    const [first, last] = [points[0], points.at(-1)];
    const excess = (point) =>
      Math.abs(
        point.height -
          (first.height +
            ((last.height - first.height) * (point.width - first.width)) /
              (last.width - first.width)),
      ) - (keep.includes(point.width) ? 1 : tolerance);
    const worst = points
      .slice(1, -1)
      .reduce((best, point) => (excess(point) > excess(best) ? point : best));
    if (excess(worst) <= 0) return [first, last];
    const split = points.indexOf(worst);
    return [
      ...Polyline.#simplify(points.slice(0, split + 1), tolerance, keep),
      ...Polyline.#simplify(points.slice(split), tolerance, keep).slice(1),
    ];
  }

  /** The height the rules give at a width: the rule with the largest `from` that does not exceed it. */
  static at(rules, width) {
    const rule = [...rules].reverse().find((candidate) => width >= candidate.from) ?? rules[0];
    return rule.intercept + rule.slope * width;
  }

  /** The CSS value: a plain length when flat, else calc(A + B vw). */
  static css({ intercept, slope }) {
    if (slope === 0) return `${intercept}px`;
    const vw = Math.round(slope * 1e5) / 1e3; // px per px of width -> vw
    return `calc(${intercept}px ${vw < 0 ? '-' : '+'} ${Math.abs(vw)}vw)`;
  }
}

/** Builds the polylines of every section and language, and prints or checks them. */
class PlaceholderCss {
  #rows;
  #tolerance;
  #switches;

  constructor({ rows, switches }, tolerance) {
    this.#rows = rows;
    this.#tolerance = tolerance;
    this.#switches = switches;
  }

  get languages() {
    return ['pt', 'en'].filter((language) => this.#rows.some((row) => row.language === language));
  }

  rulesFor(id, language) {
    const byWidth = new Map(
      this.#rows.filter((row) => row.language === language).map((row) => [row.width, row.real[id]]),
    ); // one height per width: the latest measurement
    const points = [...byWidth]
      .map(([width, height]) => ({ width, height }))
      .sort((a, b) => a.width - b.width);
    return Polyline.rules(points, this.#switches, this.#tolerance, KEEP);
  }

  /**
   * The block layout.css holds, in the style Oxfmt and Stylelint leave a file in (one declaration a line, a blank line between
   * rules, range media queries) so that formatting the file afterwards changes nothing.
   */
  css() {
    const rule = (selector, value, indent) =>
      `${indent}${selector} {\n${indent}  contain-intrinsic-size: auto ${value};\n${indent}}`;
    const sections = SECTIONS.map((id) => {
      const entries = this.languages.flatMap((language) => {
        const selector = language === 'en' ? `:lang(en) #${id}` : `#${id}`;
        return this.rulesFor(id, language).map((one) =>
          one.from === 0
            ? rule(selector, Polyline.css(one), '  ')
            : `  @media (width >= ${one.from}px) {\n${rule(selector, Polyline.css(one), '    ')}\n  }`,
        );
      });
      return [`  /* #${id} */\n${entries[0]}`, ...entries.slice(1)].join('\n\n');
    });
    return `${BLOCK_START}\n\n${sections.join('\n\n')}\n\n  ${BLOCK_END}`;
  }

  /** layout.css with the generated block replaced by this one. */
  patch(layoutCss) {
    if (!GENERATED_BLOCK.test(layoutCss))
      throw new Error(
        `${LAYOUT_CSS} has no "${BLOCK_START}" ... "${BLOCK_END}" comments to write between`,
      );
    return layoutCss.replace(GENERATED_BLOCK, () => this.css());
  }

  summary() {
    return SECTIONS.map((id) => {
      const counts = this.languages.map(
        (language) => `${language} ${this.rulesFor(id, language).length} rules`,
      );
      return `${id.padEnd(12)} ${counts.join(', ')}   (worst gap to the measurements: ${this.gaps(
        this.#rows,
      )
        .filter((gap) => gap.id === id)
        .reduce((worst, gap) => Math.max(worst, Math.abs(gap.gap)), 0)}px)`;
    }).join('\n');
  }

  /** How far the printed rules are from a set of measurements. */
  gaps(rows) {
    return rows.flatMap((row) =>
      SECTIONS.map((id) => ({
        id,
        language: row.language,
        width: row.width,
        gap: Math.round(row.real[id] - Polyline.at(this.rulesFor(id, row.language), row.width)),
      })),
    );
  }

  checkAgainst(rows) {
    const gaps = this.gaps(rows);
    return SECTIONS.map((id) => {
      const worstOf = (language) =>
        gaps
          .filter((gap) => gap.id === id && gap.language === language)
          .reduce((worst, gap) => (Math.abs(gap.gap) > Math.abs(worst.gap) ? gap : worst), {
            gap: 0,
            width: 0,
          });
      const sorted = (language) =>
        gaps
          .filter((gap) => gap.id === id && gap.language === language)
          .map((gap) => Math.abs(gap.gap))
          .sort((a, b) => a - b);
      return `${id.padEnd(12)} ${this.languages.map((language) => `${language} median ${sorted(language)[Math.floor(sorted(language).length / 2)] ?? 0}px, worst ${worstOf(language).gap}px at ${worstOf(language).width}`).join('   |   ')}`;
    }).join('\n');
  }
}

class Arguments {
  static #value(name) {
    const index = process.argv.indexOf(`--${name}`);
    return index > -1 ? process.argv[index + 1] : undefined;
  }

  static list(name, fallback) {
    const value = Arguments.#value(name);
    return value ? value.split(',').map((item) => item.trim()) : fallback;
  }

  static flag(name) {
    return process.argv.includes(`--${name}`);
  }

  /** Exits with the usage when asked for help or given a flag nobody reads, instead of starting a ten-minute measurement. */
  static check(usage) {
    const known = new Set(usage.map(([name]) => `--${name}`));
    const unknown = process.argv
      .slice(2)
      .filter((argument) => argument.startsWith('--') && !known.has(argument));
    if (!Arguments.flag('help') && unknown.length === 0) return;
    const lines = usage.map(([name, text]) => `  --${name.padEnd(13)} ${text}`);
    console.log(`Usage: node tools/measure-sections.mjs [options]\n\n${lines.join('\n')}`);
    process.exit(unknown.length === 0 ? 0 : 1);
  }
}

