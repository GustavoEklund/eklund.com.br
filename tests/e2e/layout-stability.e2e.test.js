import { test, expect } from './support/fixtures.js';
import { LayoutShiftMeter } from './support/layout-shift-meter.js';
import { DictionaryText } from './support/dictionary-text.js';

// The suite runs at 1280 px and 412 px wide, widths the placeholder polylines are anchored to, so a gap of a pixel is rounding.
const PLACEHOLDER_SLACK_PX = 1;

test.describe('layout stability', () => {
  test('a normal load has no layout shift at all', async ({ site, page }) => {
    await LayoutShiftMeter.install(page);
    await site.open('/');
    await page.waitForLoadState('networkidle');
    await page.evaluate(
      () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
    );
    expect(await LayoutShiftMeter.shifts(page)).toStrictEqual([]);
  });

  test('the English page has none either', async ({ site, page }) => {
    // The markup ships the Portuguese text and the translator swaps it. Everything is hidden until fonts-ready, the scroll cue
    // ("rola" -> "scroll", 31 px -> 47 px wide) included, so the swap happens before anything is on screen.
    await LayoutShiftMeter.install(page);
    await site.open('/en/');
    await page.waitForLoadState('networkidle');
    await page.evaluate(
      () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
    );
    expect(await LayoutShiftMeter.shifts(page)).toStrictEqual([]);
  });

  test('the scroll cue appears in English once the fonts settle', async ({
    site,
    page,
    isMobile,
  }) => {
    test.skip(isMobile, 'the cue is not shown on narrow screens');
    await site.open('/en/');
    await expect(page.locator('.scroll-cue')).toBeVisible();
    await expect(page.locator('.scroll-cue')).toHaveText(DictionaryText.of('en-US').hero.scrollCue);
  });

  test('scrolling through the whole page has none', async ({ site, page }) => {
    await LayoutShiftMeter.install(page);
    await site.open('/');
    await site.scrollThroughPage();
    expect(await LayoutShiftMeter.shifts(page)).toStrictEqual([]);
  });

  test('a lazily rendered section is as tall as the placeholder that stood in for it', async ({
    site,
    page,
  }) => {
    // #perfil, #arquitetura, #carga, #historico and #contato use content-visibility: auto, so until a section has rendered the page is laid
    // out with its contain-intrinsic-size. layout.css holds one polyline per section and language, generated by tools/measure-sections.mjs
    // from heights measured at many widths; at the widths of this suite it passes through the measurements, and anywhere else it stays
    // within a few tens of pixels. A gap here means the layout changed since the last measurement: run the tool and paste its output.
    const ids = ['perfil', 'arquitetura', 'carga', 'historico', 'contato'];
    await site.open('/');
    const reserved = await page.evaluate(
      (sections) =>
        sections.map((id) =>
          Number.parseFloat(
            getComputedStyle(document.getElementById(id)).containIntrinsicBlockSize.replace(
              'auto',
              '',
            ),
          ),
        ),
      ids,
    );
    const contentHeights = () =>
      page.evaluate(
        (sections) =>
          sections.map((id) => {
            const element = document.getElementById(id),
              style = getComputedStyle(element);
            return Math.round(
              element.clientHeight -
                Number.parseFloat(style.paddingTop) -
                Number.parseFloat(style.paddingBottom),
            );
          }),
        ids,
      );
    // Rendered, and not yet scrolled to: the load test only starts running (and growing) once it is on screen, so this is its idle height.
    const frames = () =>
      page.evaluate(
        () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
      );
    await page.evaluate(
      (sections) =>
        sections.forEach((id) =>
          document
            .getElementById(id)
            .style.setProperty('content-visibility', 'visible', 'important'),
        ),
      ids,
    );
    await frames();
    const idle = await contentHeights();
    // Every other section is read after a jump to it, once it has built what it builds when it becomes visible and its transitions have
    // ended (the history's open card grows for half a second, 130 px on a phone). Nothing is read later: the history moves on to its
    // next card every 9 s, and cards differ in height.
    const transitions = (id) =>
      page.evaluate(
        (target) =>
          Promise.all(
            document
              .getElementById(target)
              .getAnimations({ subtree: true })
              .filter((animation) => animation instanceof CSSTransition)
              .map((animation) => animation.finished.catch(() => undefined)),
          ),
        id,
      );
    const rendered = [];
    for (const [index, id] of ids.entries()) {
      if (id === 'carga') {
        rendered.push(idle[index]);
        continue;
      }
      await page.evaluate(
        (target) =>
          document.getElementById(target).scrollIntoView({ behavior: 'instant', block: 'start' }),
        id,
      );
      await frames();
      await transitions(id);
      await frames();
      rendered.push((await contentHeights())[index]);
    }
    const gaps = ids.map((id, index) => [id, Math.round(rendered[index] - reserved[index])]);
    expect(gaps.filter(([, gap]) => Math.abs(gap) > PLACEHOLDER_SLACK_PX)).toStrictEqual([]);
  });

  for (const [address, locale] of [
    ['/', 'pt-BR'],
    ['/en/', 'en-US'],
  ]) {
    test(`the contrast row is as tall before its result arrives as after it, at every width (${locale})`, async ({
      site,
      page,
    }) => {
      // The result is measured a moment after load, in slices; the row has the room of the widest result from the start.
      const measuring = DictionaryText.of(locale).status.checks.contrast.measuring;
      await site.open(address);
      await page.waitForFunction(
        (placeholder) =>
          document.querySelector('#status-components li:nth-child(8) .status-detail')
            .textContent !== placeholder,
        measuring,
      );
      const widths = [320, 360, 412, 480, 640, 720, 800, 1000, 1280];
      const heights = (placeholder) =>
        page.evaluate((text) => {
          const row = document.querySelector('#status-components li:nth-child(8)');
          const detail = row.querySelector('.status-detail');
          const result = detail.textContent;
          if (text !== null) detail.textContent = text;
          const height = row.getBoundingClientRect().height;
          detail.textContent = result;
          return height;
        }, placeholder);
      const withResult = [];
      const whileMeasuring = [];
      for (const width of widths) {
        await page.setViewportSize({ width, height: 800 });
        await page.evaluate(
          () =>
            new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
        );
        withResult.push(await heights(null));
        whileMeasuring.push(await heights(measuring));
      }
      expect(whileMeasuring).toStrictEqual(withResult);
    });
  }

  test('the status list is as tall after the page has been scrolled through as before: the globe pauses and the counts grow', async ({
    site,
    page,
  }) => {
    // The rows refresh every second. While the page is scrolled the globe leaves the screen and its row says so, the long task and request counts
    // go up, and none of that may add a line above the sections the visitor is jumping to.
    await site.open('/');
    const height = () =>
      page.evaluate(
        () => document.querySelector('#status-components').getBoundingClientRect().height,
      );
    const before = await height();
    await site.scrollThroughPage();
    await page.waitForTimeout(2500); // the globe is off the screen now, paused, and the rows have refreshed
    expect(await height()).toBe(before);
  });

  test('switching language moves nothing on the page', async ({ site, page }) => {
    await LayoutShiftMeter.install(page);
    await site.open('/');
    await page.waitForLoadState('networkidle');
    await site.localeLink('en-US').click();
    await expect(site.html).toHaveAttribute('lang', 'en-US');
    await page.evaluate(
      () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
    );
    expect(await LayoutShiftMeter.shifts(page)).toStrictEqual([]);
  });
});
